// Discovers world packs (content/worlds/<pack>/world.json) and writes world/packs.generated.ts.
// Adding a pack is a data change: drop a folder in content/worlds, no code edits (SPEC §4.4).
// Every pack is validated here, so an invalid pack fails the build.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { worldSchema } from "../world/schema";

const dir = "content/worlds";
const packs = readdirSync(dir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(join(dir, d.name, "world.json")))
  .map((d) => d.name)
  .sort();

for (const p of packs) {
  const parsed = worldSchema.safeParse(JSON.parse(readFileSync(join(dir, p, "world.json"), "utf8")));
  if (!parsed.success) {
    const issues = parsed.error.issues.map((i) => `  ${i.path.join(".")}: ${i.message}`).join("\n");
    console.error(`Invalid world pack "${p}":\n${issues}`);
    process.exit(1);
  }
}

const imports = packs.map((p, i) => `import pack${i} from "@/content/worlds/${p}/world.json";`).join("\n");
const entries = packs.map((p, i) => `  ${JSON.stringify(p)}: pack${i},`).join("\n");
writeFileSync(
  "world/packs.generated.ts",
  `// GENERATED by scripts/build-world-registry.ts. Do not edit.\n${imports}\n\nexport const RAW_PACKS: Record<string, unknown> = {\n${entries}\n};\n`,
);
console.log(`World packs: ${packs.join(", ")}`);
